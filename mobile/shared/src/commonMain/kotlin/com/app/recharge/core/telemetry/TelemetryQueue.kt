package com.app.recharge.core.telemetry

import app.cash.sqldelight.db.SqlDriver
import com.app.recharge.db.TelemetryDatabase
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

data class QueuedEvent(
    val id: String,
    val type: String,
    val name: String,
    val occurredAt: String,
    val journeyId: String?,
    val orderId: String?,
    val propsJson: String,
    val createdAt: Long,
)

/** Events waiting to be uploaded. On disk, so nothing is lost while offline or after the app is closed. */
interface TelemetryQueue {
    suspend fun insert(event: QueuedEvent)
    suspend fun count(): Int
    suspend fun oldest(limit: Int): List<QueuedEvent>
    suspend fun delete(ids: List<String>)
    suspend fun deleteOldest(n: Int)
}

/** SQLite on both platforms; the queries are generated by SQLDelight from TelemetryQueue.sq. */
class SqlTelemetryQueue(
    driver: SqlDriver,
    private val dispatcher: CoroutineDispatcher = Dispatchers.Default,
) : TelemetryQueue {

    private val queries = TelemetryDatabase(driver).telemetryQueueQueries

    override suspend fun insert(event: QueuedEvent) = withContext(dispatcher) {
        queries.insertEvent(
            event.id, event.type, event.name, event.occurredAt, event.journeyId, event.orderId,
            event.propsJson, event.createdAt,
        )
        Unit
    }

    override suspend fun count(): Int = withContext(dispatcher) { queries.countEvents().executeAsOne().toInt() }

    override suspend fun oldest(limit: Int): List<QueuedEvent> = withContext(dispatcher) {
        queries.oldest(limit.toLong()).executeAsList().map {
            QueuedEvent(it.id, it.type, it.name, it.occurred_at, it.journey_id, it.order_id, it.props_json, it.created_at)
        }
    }

    override suspend fun delete(ids: List<String>) = withContext(dispatcher) {
        if (ids.isNotEmpty()) queries.deleteByIds(ids)
        Unit
    }

    override suspend fun deleteOldest(n: Int) = withContext(dispatcher) {
        queries.deleteOldest(n.toLong())
        Unit
    }
}
